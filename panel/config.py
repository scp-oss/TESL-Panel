# ==================== panel/config.py ====================
"""
Конфигурация — всё через переменные окружения, никаких реальных серверных
путей/токенов в git (см. CLAUDE.md "Секреты и пути — не в git"). На реальном
сервере значения задаются в systemd unit-файле (infra/tesl-panel.service,
EnvironmentFile=) — сам файл со значениями НЕ коммитится, только .template.
"""
import os

# Корень хранилища на диске — на реальном сервере это примонтированный том
# (см. infra/README за инструкцией), сюда НЕ хардкодить реальный путь.
# Локально/в CI по умолчанию — относительная папка ./data, безопасна для
# тестов, никогда не используется в проде (там STORAGE_ROOT всегда задан
# явно через окружение).
STORAGE_ROOT = os.environ.get("TESL_PANEL_STORAGE_ROOT", "./data")

# Bearer-токен для /api/depot/* (запись/листинг) — тот же принцип, что и
# DAV_PASSWORD в TESL/TESL-Manager ("не секрет в строгом смысле", встроен в
# клиентские инструменты, но не публикуется в открытом виде без необходимости).
# Публичные read-эндпоинты (/ , /api/download/<...>) токен не требуют вообще.
#
# Тот же токен — единственный "пароль" в /admin (логин по нему, см.
# app.py::admin_login) — намеренно НЕ отдельный от UPLOAD_TOKEN: два
# разных секрета для одного и того же уровня доверия (кто угодно с этим
# токеном уже мог писать в депо напрямую через API) только добавили бы
# путаницы без реального повышения безопасности.
UPLOAD_TOKEN = os.environ.get("TESL_PANEL_UPLOAD_TOKEN", "")

# Подписывает cookie сессии Flask (логин в /admin) — генерируется один раз
# при первом деплое (infra/deploy.sh), хранится в panel.env, НЕ в git.
# Пустая строка по умолчанию — локальный запуск для разработки удобства
# ради; на реальном сервере deploy.sh всегда прокидывает непустое значение.
SECRET_KEY = os.environ.get("TESL_PANEL_SECRET_KEY", "dev-only-insecure-key")

# GitHub-репозитории, откуда берутся ссылки на скачивание — публичные releases,
# без токена (rate limit 60/час на IP хватает с учётом кэша ниже).
GITHUB_REPOS = {
    "launcher": {"owner": "scp-oss", "repo": "TESL", "title": "TESL (лаунчер)"},
    "manager":  {"owner": "scp-oss", "repo": "TESL-Manager", "title": "TESL-Manager"},
}

# Кэш ответа GitHub API на этот срок (секунды) — публичный API без токена
# ограничен 60 запросами/час на IP; при заметной посещаемости страницы это
# исчерпалось бы за пару минут без кэша.
GITHUB_CACHE_TTL = int(os.environ.get("TESL_PANEL_GITHUB_CACHE_TTL", "300"))

# Публичный адрес панели, каким его должен видеть клиент (TESL-Manager) —
# используется ТОЛЬКО для генерации "кода настройки" на /admin/settings
# (см. app.py::_generate_setup_code). Если не задан явно, берётся из
# request.url_root на лету — этого достаточно в обычном случае (админ и
# так заходит через реальный публичный домен за Cloudflare, тот же URL
# клиенту и нужен). Задавать явно стоит только если запрос до Flask
# доходит через прокси, искажающий Host/схему так, что url_root получается
# неверным (например, внутренний HTTP за терминацией TLS без
# X-Forwarded-Proto).
#
# TESL_PANEL_DOMAIN — прямой запрос пользователя 2026-09-23: этот env-var
# уже пишется в panel.env (deploy.sh, из --domain) и до этой правки
# приложением НЕ читался вообще — использовался только внутри самого
# deploy.sh для генерации nginx-конфига. Теперь это запасной источник для
# PUBLIC_BASE_URL (просто домен, без схемы — https:// добавляем сами,
# т.к. весь деплой этого проекта всегда за Cloudflare Full (strict) +
# nginx, HTTP как публичная схема здесь никогда не используется), на
# случай если у request.url_root/TESL_PANEL_PUBLIC_URL когда-то будет
# то же искажение прокси, что описано выше. TESL_PANEL_PUBLIC_URL, если
# задан явно, имеет приоритет — он специально существует для случаев,
# когда одного домена (без пути/нестандартного порта) недостаточно.
_PUBLIC_URL_ENV = os.environ.get("TESL_PANEL_PUBLIC_URL", "").rstrip("/")
_DOMAIN_ENV = os.environ.get("TESL_PANEL_DOMAIN", "").strip()
if _PUBLIC_URL_ENV:
    PUBLIC_BASE_URL = _PUBLIC_URL_ENV
elif _DOMAIN_ENV:
    PUBLIC_BASE_URL = f"https://{_DOMAIN_ENV}"
else:
    PUBLIC_BASE_URL = ""
